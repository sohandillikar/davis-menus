CREATE TABLE menu_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    date DATE NOT NULL,
    dining_hall TEXT NOT NULL,
    meal TEXT NOT NULL,
    platform TEXT NOT NULL,
    name TEXT NOT NULL,
    description TEXT,
    feature TEXT,
    serving_size_oz TEXT,
    calories TEXT,
    fat_g TEXT,
    carbohydrates_g TEXT,
    protein_g TEXT,
    allergens JSONB,
    diets JSONB,
    ingredients TEXT
);